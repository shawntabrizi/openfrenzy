#!/usr/bin/env python3
"""Generate src/core/crt/core_data.c: the data blocks that the core module owns.

Usage (from the repository root):
    python3 -I src/core/tools/gen_core_data.py

Why: core code (core.cpp, the CGameMode_* files, the cheat code) keeps its globals in
contiguous blocks and indexes them (players at 0x2baee0 with a 0x28 stride, the mode stack,
the cheat table at 0x283d34 with a 0x4c stride). One C variable per Ghidra DAT_ address
cannot express that. So core defines each block once, with the original layout:

  of_core_bss     [0x002ba4f0, 0x002bb138)  zero (.bss of the Core\*.obj files)
  of_core_data    [0x002839b8, 0x0028450c)  initial values from orig/default.xbe
  of_core_tweaks  [0x002ad120, 0x002adf38)  zero; set by the static constructor 0x001f2da0

Core code reads them through src/core/core_data.h (one object, so the compiler never
assumes that two fields are different objects). Every Ghidra name of an address inside a
block (DAT_, _DAT_, PTR_..., s_..., u_... in export/funcs/*.c of any module) becomes an
assembler alias "name = block + offset", so other modules that use those names, as common
or extern symbols, reach the same bytes.

Pointers inside of_core_data point into .rdata strings; they become string literals.
Any other pointer stops the generator (fail loud).
"""
import os
import re
import struct
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import xbe_data  # noqa: E402

BLOCKS = [
    # name, start, end, initialised from the XBE
    ("of_core_bss", 0x002BA4F0, 0x002BB138, False),
    ("of_core_data", 0x002839B8, 0x0028450C, True),
    ("of_core_tweaks", 0x002AD120, 0x002ADF38, False),
]

NAME_RE = re.compile(r"\b((?:_?DAT|PTR_[A-Za-z0-9_]*?|s_[A-Za-z0-9_]*?|u_[A-Za-z0-9_]*?)_(00[23][0-9a-f]{5}))\b")


def ghidra_names():
    names = {}
    funcs = os.path.join(ROOT, "export", "funcs")
    for f in sorted(os.listdir(funcs)):
        if not f.endswith(".c"):
            continue
        for full, addr in NAME_RE.findall(open(os.path.join(funcs, f), errors="replace").read()):
            names.setdefault(int(addr, 16), set()).add(full)
    return names


def c_string(raw):
    out = []
    for b in raw:
        c = chr(b)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif 32 <= b < 127:
            out.append(c)
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def main():
    d, secs = xbe_data.load()
    at = xbe_data.reader(d, secs)

    def section(v):
        for n, va, vs, ra, rs in secs:
            if va <= v < va + vs:
                return n
        return None

    def read_cstr(v):
        raw = b""
        while True:
            c = at(v + len(raw), 1)
            if c == b"\0":
                return raw
            raw += c
            if len(raw) > 512:
                sys.exit("gen_core_data: string at 0x%08x too long" % v)

    names = ghidra_names()
    out = ["/* generated by src/core/tools/gen_core_data.py from orig/default.xbe and export/funcs;",
           "   do not edit. Data blocks owned by the core module: see src/core/core_data.h. */",
           "#include <stdint.h>", ""]
    strings = {}
    body = []
    aliases = []
    for name, start, end, init in BLOCKS:
        size = end - start
        body.append("/* 0x%08x-0x%08x */" % (start, end))
        if not init:
            body.append("__attribute__((nocommon, aligned(16))) unsigned char %s[0x%x];" % (name, size))
        else:
            words = []
            for a in range(start, end, 4):
                v = struct.unpack("<I", at(a, 4))[0]
                s = section(v) if v >= 0x10000 else None
                if s is None:
                    words.append("0x%08x" % v)
                elif s == ".rdata":
                    raw = read_cstr(v)
                    if any(b < 32 or b > 126 for b in raw):
                        sys.exit("gen_core_data: 0x%08x -> 0x%08x is not a text string" % (a, v))
                    strings[v] = raw
                    words.append("(uint32_t)str_%08x" % v)
                else:
                    sys.exit("gen_core_data: 0x%08x holds a pointer 0x%08x into %s" % (a, v, s))
            body.append("__attribute__((aligned(16))) uint32_t %s[0x%x] = {" % (name, size // 4))
            for i in range(0, len(words), 4):
                body.append("\t/* 0x%08x */ %s," % (start + i * 4, ", ".join(words[i:i + 4])))
            body.append("};")
        body.append("")
        for addr in sorted(names):
            if start <= addr < end:
                for n in sorted(names[addr]):
                    aliases.append((n, name, addr - start, addr))
    for v in sorted(strings):
        out.append("static const char str_%08x[] = %s;  /* 0x%08x */" % (v, c_string(strings[v]), v))
    out.append("")
    out += body
    out.append("/* Ghidra names of addresses inside the blocks, for other modules */")
    out.append("__asm__(")
    for n, block, off, addr in aliases:
        out.append('\t".globl %s\\n.set %s, %s + 0x%x\\n"  /* 0x%08x */' % (n, n, block, off, addr))
    out.append(");")
    path = os.path.join(ROOT, "src", "core", "crt", "core_data.c")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("gen_core_data: %d aliases, %d strings -> %s" % (len(aliases), len(strings), path))


if __name__ == "__main__":
    main()
