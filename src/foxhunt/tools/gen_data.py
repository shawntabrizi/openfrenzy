#!/usr/bin/env python3
"""Generate src/foxhunt/FoxHunt/fh_data.c: the initialised Fox Hunt data blocks of the XBE
.data section as 32-bit words, with the pointers in them turned into symbols (analysis
helper of the foxhunt module; same design as src/mousewhack/tools/gen_data.py).

Blocks (the gaps between them belong to other modules):
  fh_data_a  [0x002ab26c, 0x002ad120)  actor/model tables, start positions, particle types
                                       (core's tweak block starts at 0x002ad120)
  fh_data_b  [0x002adf38, 0x002ae578)  throwables, sharks, glass, escalators, goals
                                       (classlib_fx CWaterField data starts at 0x002ae578)
  fh_data_c  [0x002ae5c0, 0x002ae7b4)  player state names and the AI state vtables
                                       (classlib_fx AI data starts at 0x002ae7b4)

A word becomes a symbol when it is the address of a printable string in .rdata/.data,
the start of a known function, or an address inside one of the blocks above or inside
core's tweak block. Every other word is copied as a number.

Usage: python3 -I src/foxhunt/tools/gen_data.py
"""
import os
import struct
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import xbe_data  # noqa: E402

BLOCKS = [("fh_data_a", 0x002ab26c, 0x002ad120),
          ("fh_data_b", 0x002adf38, 0x002ae578),
          ("fh_data_c", 0x002ae5c0, 0x002ae7b4)]
CORE_TWEAKS = (0x002ad120, 0x002adf38)


def c_string(raw):
    out = []
    for b in raw:
        if b == 0x5c:
            out.append("\\\\")
        elif b == 0x22:
            out.append('\\"')
        elif 32 <= b < 127:
            out.append(chr(b))
        else:
            out.append("\\x%02x" % b)
    return '"' + "".join(out) + '"'


def main():
    d, secs = xbe_data.load()
    at = xbe_data.reader(d, secs)
    funcs = xbe_data.function_names()

    def section(v):
        for name, va, vs, _, _ in secs:
            if va <= v < va + vs:
                return name
        return None

    def string_at(w):
        raw = b""
        while len(raw) < 256:
            c = at(w + len(raw), 1)
            if c == b"\0":
                break
            raw += c
        if raw and all(32 <= c < 127 for c in raw):
            return raw
        return None

    def symbol(w):
        """The C expression for pointer value w, or None when w is a plain number."""
        if w < 0x11000 or w >= 0x0031d978:
            return None
        sec = section(w)
        if sec == ".text":
            return "FUN_%08x" % w if w in funcs else None
        if sec not in (".rdata", ".data"):
            return None
        for name, lo, hi in BLOCKS:
            if lo <= w < hi:
                return "(unsigned char *)%s + 0x%x" % (name, w - lo)
        if CORE_TWEAKS[0] <= w < CORE_TWEAKS[1]:
            return "of_core_tweaks + 0x%x" % (w - CORE_TWEAKS[0])
        s = string_at(w)
        if s is not None:
            return c_string(s)
        return None

    out = []
    for name, lo, hi in BLOCKS:
        out.append("/* 0x%08x-0x%08x */" % (lo, hi))
        out.append("uint32_t %s[0x%x / 4] __attribute__((aligned(16))) = {" % (name, hi - lo))
        for a in range(lo, hi, 4):
            w, = struct.unpack("<I", at(a, 4))
            sym = symbol(w)
            if sym is not None:
                out.append("\t/* 0x%08x */ FH_PTRWORD(%s)," % (a, sym))
            else:
                out.append("\t/* 0x%08x */ 0x%08xu," % (a, w))
        out.append("};")
        out.append("")
    path = os.path.join(ROOT, "src", "foxhunt", "FoxHunt", "fh_data.c")
    with open(path, "w") as f:
        f.write("""/*
FoxHunt/fh_data.c  (module foxhunt; generated by src/foxhunt/tools/gen_data.py, do not edit)

The initialised Fox Hunt data blocks of the XBE .data section, word for word. Pointers in
them (model and texture names, the particle type table, the AI state vtables) are symbols.
Code reaches the words through FH_ADDR()/FH_VAR() in foxhunt_data.h.
*/

#include "foxhunt.h"

#define FH_PTRWORD(p) ((uint32_t)(uintptr_t)(p))

/* core: the tweak block 0x002ad120-0x002adf38 (core_data.h); the particle type table
points into it */
extern unsigned char of_core_tweaks[];

""")
        f.write("\n".join(out))
    print("wrote", path)


if __name__ == "__main__":
    main()
