/* bKernel 0x00051540: the squared distance of two points. bkernel defines it as an empty
function (bmNothing2), which is wrong (the original computes this); a local copy until
bkernel fixes it. */
static inline float fh_DistanceSquared(const float *a, const float *b)
{
	float x = a[0] - b[0];
	float y = a[1] - b[1];
	float z = a[2] - b[2];
	return z * z + x * x + y * y;   /* the original order */
}

/* MSVC rand(), inlined into the game: holdrand is the C library's seed at 0x00285630 */
extern unsigned int DAT_00285630;
static inline int fh_rand(void)
{
	DAT_00285630 = DAT_00285630 * 0x343fdu + 0x269ec3u;
	return (int)((DAT_00285630 >> 16) & 0x7fff);
}

/* a float's bit pattern, for an undefined4 parameter that carries a float */
static inline unsigned int fh_fbits(float value)
{
	unsigned int bits;
	memcpy(&bits, &value, sizeof bits);
	return bits;
}

static inline float fh_bitsf(unsigned int bits)
{
	float value;
	memcpy(&value, &bits, sizeof value);
	return value;
}

