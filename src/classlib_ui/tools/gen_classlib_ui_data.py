#!/usr/bin/env python3
"""Generate src/classlib_ui/ClassLib/classlib_ui_data.c: the data blocks owned by classlib_ui.

Usage (from the repository root):
    python3 -I src/classlib_ui/tools/gen_classlib_ui_data.py

Adapted from src/core/tools/gen_core_data.py (same design, see its docstring): ClassLib code
indexes its globals as tables (sample sets with a 0x34 stride, the character table with a
0x60 stride, HUD and pause-menu vertex arrays), so each block is defined once with the
original layout, and every Ghidra name inside a block (from export/funcs/*.c of any module)
becomes an assembler alias "name = block + offset" for the other modules (and DAT_<addr>
too, when Ghidra only wrote PTR_... or s_... there).

Blocks:
  of_clu_data   [0x0028fda8, 0x00290cc0)  .data of ClassLib block 1 (XBE values)
  of_clu_data2  [0x00290d14, 0x00290d54)  .data of CRumble.cpp (XBE values)
  of_clu_bss    [0x002ea490, 0x002ed33c)  .bss of ClassLib block 1 (zero)

A word of .data becomes a pointer only when it points at a text string in .rdata (ASCII
or UTF-16) or exactly at a game function start (of_functions.tsv); every other value
inside an XBE section is listed on stderr for review and kept as a number (colours like
0x00125317 look like .text addresses). NOT_POINTERS lists the reviewed ones.
"""
import os
import re
import struct
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import xbe_data  # noqa: E402

BLOCKS = [
    ("of_clu_data", 0x0028FDA8, 0x00290CC0, True),
    ("of_clu_data2", 0x00290D14, 0x00290D54, True),
    ("of_clu_bss", 0x002EA490, 0x002ED33C, False),
]

# reviewed words that look like addresses but are numbers (character colours)
NOT_POINTERS = {0x00290718, 0x00290898}

NAME_RE = re.compile(r"\b((?:_?DAT|PTR_[A-Za-z0-9_]*?|s_[A-Za-z0-9_]*?|u_[A-Za-z0-9_]*?)_(00[23][0-9a-f]{5}))\b")


def ghidra_names():
    names = {}
    funcs = os.path.join(ROOT, "export", "funcs")
    for f in sorted(os.listdir(funcs)):
        if not f.endswith(".c"):
            continue
        for full, addr in NAME_RE.findall(open(os.path.join(funcs, f), errors="replace").read()):
            names.setdefault(int(addr, 16), set()).update((full, "DAT_" + addr))
    return names


def function_starts():
    starts = set()
    for line in open(os.path.join(ROOT, "src", "include", "of_functions.tsv")):
        if not line.startswith("#"):
            starts.add(int(line.split("\t", 1)[0], 16))
    return starts


def c_string(raw):
    out = []
    for b in raw:
        c = chr(b)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif 32 <= b < 127:
            out.append(c)
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def main():
    d, secs = xbe_data.load()
    at = xbe_data.reader(d, secs)

    def section(v):
        for n, va, vs, ra, rs in secs:
            if va <= v < va + vs:
                return n
        return None

    def ascii_at(v):
        raw = b""
        while len(raw) < 512:
            c = at(v + len(raw), 1)
            if c == b"\0":
                return raw if all(32 <= b < 127 or b in (9, 10) for b in raw) else None
            raw += c
        return None

    def utf16_at(v):
        units = []
        while len(units) < 512:
            u = struct.unpack("<H", at(v + 2 * len(units), 2))[0]
            if u == 0:
                return units if units and all(32 <= x < 127 or x in (9, 10) for x in units) else None
            units.append(u)
        return None

    names = ghidra_names()
    starts = function_starts()
    out = ["/* generated by src/classlib_ui/tools/gen_classlib_ui_data.py from orig/default.xbe and",
           "   export/funcs; do not edit. Data blocks owned by classlib_ui: see classlib_ui_data.h. */",
           "#include <stdint.h>", ""]
    strings = {}
    wstrings = {}
    funcs = set()
    body = []
    aliases = []
    review = []
    for name, start, end, init in BLOCKS:
        size = end - start
        body.append("/* 0x%08x-0x%08x */" % (start, end))
        if not init:
            body.append("__attribute__((nocommon, aligned(16))) unsigned char %s[0x%x];" % (name, size))
        else:
            words = []
            for a in range(start, end, 4):
                v = struct.unpack("<I", at(a, 4))[0]
                s = section(v) if v >= 0x10000 and a not in NOT_POINTERS else None
                wide = utf16_at(v) if s == ".rdata" else None
                if wide is not None and len(wide) > 1 and len(ascii_at(v) or b"") <= 1:
                    wstrings[v] = wide
                    words.append("(uint32_t)wstr_%08x" % v)
                elif s == ".rdata" and ascii_at(v) is not None:
                    strings[v] = ascii_at(v)
                    words.append("(uint32_t)str_%08x" % v)
                elif s == ".text" and v in starts:
                    funcs.add(v)
                    words.append("(uint32_t)FUN_%08x" % v)
                else:
                    if s is not None:
                        review.append("0x%08x holds 0x%08x (%s): kept as a number" % (a, v, s))
                    words.append("0x%08x" % v)
            body.append("__attribute__((aligned(16))) uint32_t %s[0x%x] = {" % (name, size // 4))
            for i in range(0, len(words), 4):
                body.append("\t/* 0x%08x */ %s," % (start + i * 4, ", ".join(words[i:i + 4])))
            body.append("};")
        body.append("")
        for addr in sorted(names):
            if start <= addr < end:
                for n in sorted(names[addr]):
                    aliases.append((n, name, addr - start, addr))
    for v in sorted(strings):
        out.append("static const char str_%08x[] = %s;  /* 0x%08x */" % (v, c_string(strings[v]), v))
    for v in sorted(wstrings):
        text = "".join(chr(u) for u in wstrings[v])
        out.append("static const __CHAR16_TYPE__ wstr_%08x[] = u%s;  /* 0x%08x */"
                   % (v, c_string(text.encode("latin1")), v))
    out.append("")
    if funcs:
        out.append("/* functions referenced by the tables (declared in of_decls.h) */")
        out.append("")
    out += body
    out.append("/* Ghidra names of addresses inside the blocks, for other modules */")
    out.append("__asm__(")
    for n, block, off, addr in aliases:
        out.append('\t".globl %s\\n.set %s, %s + 0x%x\\n"  /* 0x%08x */' % (n, n, block, off, addr))
    out.append(");")
    path = os.path.join(ROOT, "src", "classlib_ui", "ClassLib", "classlib_ui_data.c")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    for line in review:
        print("review: " + line, file=sys.stderr)
    print("gen_classlib_ui_data: %d aliases, %d strings, %d wide strings, %d functions -> %s"
          % (len(aliases), len(strings), len(wstrings), len(funcs), path))


if __name__ == "__main__":
    main()
