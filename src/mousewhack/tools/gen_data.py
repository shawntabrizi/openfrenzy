#!/usr/bin/env python3
"""Generate src/mousewhack/MouseWhack/mw_data.c: the initialised MouseWhack data block
(0x002b26b8-0x002b4b8c in the XBE .data section) as 32-bit words, with the pointers in it
(strings, functions) turned into symbols (analysis helper of the mousewhack module).

Usage: python3 -I src/mousewhack/tools/gen_data.py
"""
import os
import struct
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import xbe_data  # noqa: E402

DATA_LO = 0x002b26b8
DATA_HI = 0x002b4b8c

# words of the block that hold pointers: 3 string tables of {name, resource} pairs and two vtables
STRING_PTRS = list(range(0x002b26b8, 0x002b2718, 8)) + list(range(0x002b41dc, 0x002b4214, 8)) \
    + list(range(0x002b4218, 0x002b4260, 8))
FUNC_PTRS = list(range(0x002b4b3c, 0x002b4b84, 4))


def c_string(raw):
    out = []
    for b in raw:
        if b == 0x5c:
            out.append("\\\\")
        elif b == 0x22:
            out.append('\\"')
        elif 32 <= b < 127:
            out.append(chr(b))
        else:
            out.append("\\x%02x" % b)
    return '"' + "".join(out) + '"'


def main():
    d, secs = xbe_data.load()
    at = xbe_data.reader(d, secs)
    lines = []
    for a in range(DATA_LO, DATA_HI, 4):
        w, = struct.unpack("<I", at(a, 4))
        if a in STRING_PTRS:
            raw = b""
            while at(w + len(raw), 1) != b"\0":
                raw += at(w + len(raw), 1)
            lines.append("\t/* 0x%08x */ MW_PTRWORD(%s)," % (a, c_string(raw)))
        elif a in FUNC_PTRS:
            lines.append("\t/* 0x%08x */ MW_PTRWORD(FUN_%08x)," % (a, w))
        else:
            lines.append("\t/* 0x%08x */ 0x%08xu," % (a, w))
    out = os.path.join(ROOT, "src", "mousewhack", "MouseWhack", "mw_data.c")
    with open(out, "w") as f:
        f.write("""/*
MouseWhack/mw_data.c  (module mousewhack; generated by src/mousewhack/tools/gen_data.py, do not edit)

The initialised MouseWhack data block, 0x%08x-0x%08x of the XBE .data section, word for
word. Pointers in it (actor/model name tables, the CBbash player vtables at 0x002b4b3c and
0x002b4b60) are symbols. Code reaches the words through MW_A()/MW_F()/... in mousewhack.h.
*/

#include "mousewhack.h"

#define MW_PTRWORD(p) ((uint32_t)(uintptr_t)(p))

uint32_t mw_data[0x%x / 4] __attribute__((aligned(16))) = {
%s
};
""" % (DATA_LO, DATA_HI, DATA_HI - DATA_LO, "\n".join(lines)))
    print("wrote", out)


if __name__ == "__main__":
    main()
