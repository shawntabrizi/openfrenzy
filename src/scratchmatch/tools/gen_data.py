#!/usr/bin/env python3
"""Generate src/scratchmatch/ScratchMatch/sm_data.c: the initialised ScratchMatch data block
(0x002b5b60-0x002b6950 in the XBE .data section) as 32-bit words, with the pointers in it
(strings, pointers into the block itself) turned into symbols (analysis helper of the
scratchmatch module).

Usage: python3 -I src/scratchmatch/tools/gen_data.py
"""
import os
import struct
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import xbe_data  # noqa: E402

DATA_LO = 0x002b5b60
DATA_HI = 0x002b6950

# words of the block that hold string pointers: package names, sample names, music names,
# camera paths, direction sprites, light pod models, the "SMOKE" effect name, animation
# names and the HUD sprite names
STRING_PTRS = list(range(0x002b5b64, 0x002b5ba8, 4)) + list(range(0x002b5bac, 0x002b5bb8, 4)) \
    + list(range(0x002b5d90, 0x002b5d9c, 4)) + [0x002b5e34, 0x002b5e38, 0x002b5f10] \
    + list(range(0x002b5f98, 0x002b5fb4, 4)) + list(range(0x002b68d8, 0x002b6944, 4))
# words that point into the block itself (the smoke sprite definition and its effect)
SELF_PTRS = [0x002b5e88, 0x002b5f14, 0x002b5f1c]


def c_string(raw):
    out = []
    for b in raw:
        if b == 0x5c:
            out.append("\\\\")
        elif b == 0x22:
            out.append('\\"')
        elif 32 <= b < 127:
            out.append(chr(b))
        else:
            out.append("\\x%02x" % b)
    return '"' + "".join(out) + '"'


def main():
    d, secs = xbe_data.load()
    at = xbe_data.reader(d, secs)
    lines = []
    for a in range(DATA_LO, DATA_HI, 4):
        w, = struct.unpack("<I", at(a, 4))
        if a in STRING_PTRS:
            raw = b""
            while at(w + len(raw), 1) != b"\0":
                raw += at(w + len(raw), 1)
            lines.append("\t/* 0x%08x */ SM_PTRWORD(%s)," % (a, c_string(raw)))
        elif a in SELF_PTRS:
            assert DATA_LO <= w < DATA_HI, hex(a)
            lines.append("\t/* 0x%08x */ SM_PTRWORD((char *)sm_data + 0x%x),  /* -> 0x%08x */"
                         % (a, w - DATA_LO, w))
        else:
            lines.append("\t/* 0x%08x */ 0x%08xu," % (a, w))
    out = os.path.join(ROOT, "src", "scratchmatch", "ScratchMatch", "sm_data.c")
    with open(out, "w") as f:
        f.write("""/*
ScratchMatch/sm_data.c  (module scratchmatch; generated by src/scratchmatch/tools/gen_data.py, do not edit)

The initialised ScratchMatch data block, 0x%08x-0x%08x of the XBE .data section, word for
word. Pointers in it (name tables, the smoke sprite definition's pointers into the block) are
symbols. Code reaches the words through SM_A()/SM_F()/... in scratchmatch.h.
*/

#include "scratchmatch.h"

#define SM_PTRWORD(p) ((uint32_t)(uintptr_t)(p))

uint32_t sm_data[0x%x / 4] __attribute__((aligned(16))) = {
%s
};
""" % (DATA_LO, DATA_HI, DATA_HI - DATA_LO, "\n".join(lines)))
    print("wrote", out)


if __name__ == "__main__":
    main()
