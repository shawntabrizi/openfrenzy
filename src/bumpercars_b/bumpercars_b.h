/* a high resolution timer (gap functions 0x00096320-0x00096670; the same class is in
TankedUp: 0x001c36e0 sets the duration, 0x001c3770 pauses, 0x001d5950 is the destructor) */
struct BCarTimer {
	unsigned char running;         /* 0x00 */
	unsigned char paused;          /* 0x01 */
	unsigned char pad02[6];
	unsigned long long start;      /* 0x08 tick of the start (moved on by pauses) */
	unsigned long long frequency;  /* 0x10 ticks per second */
	unsigned long long pauseStart; /* 0x18 */
	unsigned long long last;       /* 0x20 tick of the last update */
	float duration;                /* 0x28 seconds (a count down when nonzero) */
	float durationMs;              /* 0x2c */
	float frames;                  /* 0x30 frames (at 60 Hz) since the last update */
	float remaining;               /* 0x34 seconds left */
	float fraction;                /* 0x38 elapsed / duration, 1.0 when done */
	float elapsed;                 /* 0x3c seconds */
	float frameTime;               /* 0x40 seconds since the last update */
	float averageFrame;            /* 0x44 */
	float totalFrameTime;          /* 0x48 */
	int pad4c;
	unsigned long long updates;    /* 0x50 */
};
