/*
BUMPERCARS_B.H

Module bumpercars_b: the BumperCars minigame, part 2 (0x00096240-0x000a8250): the timer
class, CBCar_Player, CBCar_Entity (cars, pucks, keepsakes, powerups), CBCar_World (the arena
and its physics), floaty scores, pucks, powerups, keepsakes, explosions, waypoints (the AI
paths), skid tracks, headlights, the generic goal and the gap functions between them.

Owner: bumpercars_b. Other modules may include this header; only bumpercars_b edits it.

Conventions (docs/ARCHITECTURE.md):
- Layouts are the original 32-bit ones; offsets are checked with OF_ASSERT_OFFSET.
- Methods take the object as the first parameter (the x86 code passed it in ECX).
- Calls into other modules whose table prototype has the wrong shape (a lost ECX `this`, a
  float typed undefined4, a lost return value) go through BCB_CALL with the real shape.
- The BumperCars .bss (0x002ed458-0x002f27c4) is one block, of_bcb_bss, defined by
  BumperCars/bcb_data.c (generated by tools/gen_bcb_data.py). Code here reaches it through
  BCB_VAR / the named macros below, so that the compiler never assumes two fields of the
  block are different objects (the original code indexes across them). Other modules keep
  the Ghidra names (DAT_002efba8, ...): bcb_data.c defines them as aliases into the block.
  bumpercars_a must declare them extern, not define them.
- .rdata constants are written as literals with their address in a comment.
- x87 compares: Ghidra's "(a < b) != (a == b)" means a <= b; they are written as plain compares.
*/

