#!/usr/bin/env python3
"""Generate src/bumpercars_b/BumperCars/bcb_data.c: the BumperCars .bss block (zero) and the
Ghidra names (DAT_<addr>) of every address inside it that any function in export/funcs or any
other module's source references, as aliases into the block (analysis helper of the bumpercars_b module).

Usage: python3 -I src/bumpercars_b/tools/gen_bcb_data.py
"""
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
START = 0x002ed458
END = 0x002f27c4
OUT = os.path.join(ROOT, "src", "bumpercars_b", "BumperCars", "bcb_data.c")


def main():
    names = {START}  # DAT_002ed458: the CBCar_Game object (bumpercars_a), start of the block
    # objects the code passes in ECX (mov ecx, imm32), which Ghidra's C does not name
    names |= {0x002ed470, 0x002ed4b4, 0x002efa98, 0x002efba8, 0x002f0768, 0x002f0778, 0x002f0a5c,
              0x002f1380, 0x002f1fa8}
    rx = re.compile(r"\bDAT_([0-9a-f]{8})\b")
    funcs = os.path.join(ROOT, "export", "funcs")
    for name in os.listdir(funcs):
        for m in rx.finditer(open(os.path.join(funcs, name)).read()):
            v = int(m.group(1), 16)
            if START <= v < END:
                names.add(v)
    # and every name other modules' sources use (functions found later, other analyses)
    src = os.path.join(ROOT, "src")
    for top, dirs, files in os.walk(src):
        if os.path.relpath(top, src).split(os.sep)[0] == "bumpercars_b":
            continue
        for f in files:
            if f.endswith((".c", ".h", ".inc")):
                for m in rx.finditer(open(os.path.join(top, f), errors="replace").read()):
                    v = int(m.group(1), 16)
                    if START <= v < END:
                        names.add(v)
    lines = [
        "/* generated by src/bumpercars_b/tools/gen_bcb_data.py from export/funcs; do not edit.",
        "   The BumperCars .bss block (owned by bumpercars_b, see bumpercars_b.h) and the Ghidra",
        "   names of the addresses inside it, as aliases for every module. */",
        "",
        "/* 0x%08x-0x%08x */" % (START, END),
        "__attribute__((nocommon, aligned(16))) unsigned char of_bcb_bss[0x%x];" % (END - START),
        "",
        "__asm__(",
    ]
    for v in sorted(names):
        lines.append('\t".globl DAT_%08x\\n.set DAT_%08x, of_bcb_bss + 0x%x\\n"' % (v, v, v - START))
    lines.append(");")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print("%d aliases -> %s" % (len(names), OUT))


if __name__ == "__main__":
    main()
