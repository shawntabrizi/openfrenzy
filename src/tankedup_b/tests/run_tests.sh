#!/bin/sh
# Builds and runs the tankedup_b module's tests (tankedup_b_test.c) as one guest image.
#
#   src/tankedup_b/tests/run_tests.sh [build dir]     (default: build-tankedup_b)
#
# Needs a configured project build in that directory (cmake -S . -B <dir>). Builds only what
# the test needs (the tankedup_b objects, the weak stubs, the guest runtime, the platform
# layer, musl), so other modules' build errors do not stop it. (Copied from
# src/clusteroids/tests/run_tests.sh, itself adapted from bumpercars_b.)
#
# Difference: the tankedup_b code reads data that other modules own (core's player table,
# classlib_ui's HUD, ...). Those modules are not linked, so this script lists the symbols that
# nothing in the test image defines and gives each one a zero, 0x400-byte data slot
# (foreign.c, printed to foreign.txt). The tests only call code that needs no such data
# except what the test sets itself. A function among those symbols would crash if called;
# the script prints every name so that a reader can see them.
set -eu

root=$(cd "$(dirname "$0")/../../.." && pwd)
build=${1:-build-tankedup_b}
case "$build" in /*) ;; *) build="$root/$build" ;; esac
guest="$build/guest-main"
test_src="$root/src/tankedup_b/tests/tankedup_b_test.c"
out="$build/tankedup_b-tests"
image="$out/tankedup_b_test.elf"
mkdir -p "$out/data" "$out/saves"

cmake --build "$guest" -t game_decls >/dev/null
objects_all=$(ninja -C "$guest" -t targets all | grep -o "[^ :]*src/tankedup_b/[^ :]*\.c\.obj" | sort -u)
ninja -C "$guest" $objects_all game_stubs guest_runtime ofplatform guestc >/dev/null

commands=$(ninja -C "$guest" -t commands openfrenzy_guest)
compile=$(printf '%s\n' "$commands" | grep -F 'tankedup_b/TankedUp/CTank_Sound.c' | grep -F ' -c ' | tail -n 1)
link=$(printf '%s\n' "$commands" | grep -F 'ld.lld' | tail -n 1)
if [ -z "$compile" ] || [ -z "$link" ]; then
	echo "run_tests.sh: no game build commands in $guest (configure the project first)" >&2
	exit 2
fi
llvm_bin=$(printf '%s\n' "$compile" | sed -e 's/.*--of-llvm-bin=\([^ ]*\).*/\1/')

# compile_one SOURCE OBJECT: the CTank_Sound.c command for another source
compile_one() {
	cmd=$(printf '%s\n' "$compile" | sed \
		-e 's/ -MD -MT [^ ]* -MF [^ ]*//' \
		-e "s# -o [^ ]* # -DOPENFRENZY_TANKEDUP_B_TEST=1 -o $2 #" \
		-e "s# -c [^ ]*\$# -c $1#")
	(cd "$guest" && eval "$cmd")
}
compile_one "$test_src" "$out/tankedup_b_test.o"

objects=$(printf '%s\n' "$link" | tr ' ' '\n' | grep -E '\.obj$' |
	grep -E 'guest_runtime\.dir|game_stubs\.dir|/src/tankedup_b/' | grep -v '/tests/')
libs=$(printf '%s\n' "$link" | tr ' ' '\n' | grep -E '\.a$')
lld=$(printf '%s\n' "$link" | tr ' ' '\n' | grep -E 'ld\.lld$' | head -n 1)
script=$(printf '%s\n' "$link" | sed -e 's/.* -T \([^ ]*\) .*/\1/')

# the symbols that the tankedup_b objects and the test need and nothing linked defines
(cd "$guest" && "$llvm_bin/llvm-nm" -u -j $(printf '%s\n' $objects | grep /src/tankedup_b/) \
	"$out/tankedup_b_test.o") | grep -v ':$' | sort -u > "$out/needed.txt"
(cd "$guest" && "$llvm_bin/llvm-nm" --defined-only -j $objects "$out/tankedup_b_test.o" \
	$(printf '%s\n' $libs) 2>/dev/null) | grep -v ':$' | sort -u > "$out/defined.txt"
comm -23 "$out/needed.txt" "$out/defined.txt" > "$out/foreign.txt"
{
	echo "/* generated by src/tankedup_b/tests/run_tests.sh: zero data for other modules' symbols */"
	while read -r sym; do
		echo "__attribute__((aligned(16))) unsigned char $sym[0x400];"
	done < "$out/foreign.txt"
} > "$out/foreign.c"
echo "foreign symbols given zero data: $(wc -l < "$out/foreign.txt" | tr -d ' ') (list: $out/foreign.txt)"
compile_one "$out/foreign.c" "$out/foreign.o"

(cd "$guest" && $lld -m aarch64linux -static -nostdlib -T "$script" $objects "$out/tankedup_b_test.o" \
	"$out/foreign.o" --whole-archive $(printf '%s\n' $libs | grep ofplatform) --no-whole-archive \
	$(printf '%s\n' $libs | grep -v ofplatform) -o "$image")

export OPENFRENZY_DATA_ROOT="$out/data" OPENFRENZY_SAVE_ROOT="$out/saves" OPENFRENZY_WINDOWED=1
export SDL_VIDEO_DRIVER="${SDL_VIDEO_DRIVER-dummy}"

set +e
perl -e 'alarm shift; exec @ARGV or die' "${OF_TEST_TIMEOUT:-60}" "$build/openfrenzy" "$image" \
	> "$out/test.log" 2>&1
status=$?
set -e
grep -E 'FAIL|tankedup_b tests|Game exited' "$out/test.log" || true
if [ $status -eq 0 ] && grep -q "Game exited (0)" "$out/test.log"; then
	echo "PASS tankedup_b_test"
	exit 0
fi
echo "FAIL tankedup_b_test (exit $status, log $out/test.log)"
exit 1
