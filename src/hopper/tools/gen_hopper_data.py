#!/usr/bin/env python3
"""Generate src/hopper/Hopper/hopper_data.c: the data blocks owned by hopper.

Usage (from the repository root):
    python3 -I src/hopper/tools/gen_hopper_data.py

Adapted from src/classlib_fx/tools (itself from src/core/tools/gen_core_data.py; same
design, see their docstrings): each block is defined once with the original layout and the
XBE's initial values, and every name of an address inside a block becomes an assembler
alias "name = block + offset". The names are the Ghidra names in export/funcs/*.c of any
module, plus DAT_<addr> for every word of a block, except in EXCLUDE.

Blocks:
  of_hop_data  [0x002ae814, 0x002b04e4)  .data of Hopper (XBE values): the character model
                                         table, the antics/resources/arena/effects objects
                                         and their tables, the player AI state tables
  of_hop_bss   [0x003023d4, 0x00304558)  .bss of Hopper (zero); core's static constructors
                                         construct the objects at 0x003024c8 (the route
                                         object) and 0x00302798 (the game object) in it

A word of .data becomes a pointer when it points at a text string in .rdata, at a game
function start, into its own block, at one of hopper's vtables (VTABLES), or at an address
in DATA_POINTERS (another module's data). Every other value inside an XBE section stops the
generator (fail loud), except the words in LITERALS (byte tables that look like addresses).
"""
import os
import re
import struct
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import xbe_data  # noqa: E402

BLOCKS = [
    ("of_hop_data", 0x002AE814, 0x002B04E4, True),
    ("of_hop_bss", 0x003023D4, 0x00304558, False),
]

EXCLUDE = []

# data addresses of other modules that this module's tables point at
DATA_POINTERS = set()

# .rdata tables (vtables) that hopper defines as vtable_<addr>
VTABLES = {0x0026E330, 0x0026E510, 0x0026EDB8, 0x0026EDD4, 0x0026EEB4, 0x0026EEB8, 0x0026F038,
           0x0026F05C}

# words that look like addresses but are numbers (colours, byte tables), by the address of the word
LITERALS = {0x002AF508, 0x002AF54C, 0x002B0390, 0x002B03CC, 0x002B0408, 0x002B0430}

NAME_RE = re.compile(r"\b((?:_?DAT|PTR_[A-Za-z0-9_]*?|s_[A-Za-z0-9_]*?|u_[A-Za-z0-9_]*?)_(00[23][0-9a-f]{5}))\b")


def excluded(addr):
    return any(lo <= addr < hi for lo, hi in EXCLUDE)


def ghidra_names():
    names = {}
    funcs = os.path.join(ROOT, "export", "funcs")
    for f in sorted(os.listdir(funcs)):
        if not f.endswith(".c"):
            continue
        for full, addr in NAME_RE.findall(open(os.path.join(funcs, f), errors="replace").read()):
            names.setdefault(int(addr, 16), set()).update((full, "DAT_" + addr))
    return names


def function_starts():
    starts = set()
    for line in open(os.path.join(ROOT, "src", "include", "of_functions.tsv")):
        if not line.startswith("#"):
            starts.add(int(line.split("\t", 1)[0], 16))
    return starts


def c_string(raw):
    out = []
    for b in raw:
        c = chr(b)
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif 32 <= b < 127:
            out.append(c)
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def main():
    d, secs = xbe_data.load()
    at = xbe_data.reader(d, secs)

    def section(v):
        for n, va, vs, ra, rs in secs:
            if va <= v < va + vs:
                return n
        return None

    def ascii_at(v):
        raw = b""
        while len(raw) < 512:
            c = at(v + len(raw), 1)
            if c == b"\0":
                return raw if all(32 <= b < 127 or b in (9, 10) for b in raw) else None
            raw += c
        return None

    names = ghidra_names()
    starts = function_starts()
    out = ["/* generated by src/hopper/tools/gen_hopper_data.py from orig/default.xbe and",
           "   export/funcs; do not edit. Data blocks owned by hopper: see the generator docstring. */",
           "#include <stdint.h>", ""]
    strings = {}
    funcs = set()
    datap = set()
    vtabs = set()
    body = []
    aliases = []
    errors = []
    for name, start, end, init in BLOCKS:
        size = end - start
        body.append("/* 0x%08x-0x%08x */" % (start, end))
        if not init:
            body.append("__attribute__((nocommon, aligned(16))) unsigned char %s[0x%x];" % (name, size))
        else:
            words = []
            for a in range(start, end, 4):
                v = struct.unpack("<I", at(a, 4))[0]
                s = section(v) if v >= 0x10000 else None
                if a in LITERALS:
                    words.append("0x%08x" % v)
                elif v in VTABLES:
                    vtabs.add(v)
                    words.append("(uint32_t)vtable_%08x" % v)
                elif s == ".rdata" and ascii_at(v) is not None:
                    strings[v] = ascii_at(v)
                    words.append("(uint32_t)str_%08x" % v)
                elif s == ".text" and v in starts:
                    funcs.add(v)
                    words.append("(uint32_t)FUN_%08x" % v)
                elif start <= v < end:
                    words.append("(uint32_t)((unsigned char *)%s + 0x%x)" % (name, v - start))
                elif v in DATA_POINTERS:
                    datap.add(v)
                    words.append("(uint32_t)DAT_%08x" % v)
                else:
                    if s is not None:
                        errors.append("0x%08x holds 0x%08x (%s): add it to DATA_POINTERS or "
                                      "review it" % (a, v, s))
                    words.append("0x%08x" % v)
            body.append("__attribute__((aligned(16))) uint32_t %s[0x%x] = {" % (name, size // 4))
            for i in range(0, len(words), 4):
                body.append("\t/* 0x%08x */ %s," % (start + i * 4, ", ".join(words[i:i + 4])))
            body.append("};")
        body.append("")
        block_names = {}
        for addr in range(start, end, 4):
            block_names.setdefault(addr, set()).add("DAT_%08x" % addr)
        for addr in names:
            if start <= addr < end:
                block_names.setdefault(addr, set()).update(names[addr])
        for addr in sorted(block_names):
            if excluded(addr):
                continue
            for n in sorted(block_names[addr]):
                aliases.append((n, name, addr - start, addr))
    if errors:
        for e in errors:
            print("gen_hopper_data: error: " + e, file=sys.stderr)
        sys.exit(1)
    for v in sorted(strings):
        out.append("static const char str_%08x[] = %s;  /* 0x%08x */" % (v, c_string(strings[v]), v))
    out.append("")
    if funcs:
        out.append("/* functions referenced by the tables (declared in of_decls.h) */")
        out.append("")
    if vtabs:
        out.append("/* hopper's vtables (in the Hopper .c files) */")
        for v in sorted(vtabs):
            out.append("extern const void *const vtable_%08x[];" % v)
        out.append("")
    if datap:
        out.append("/* other modules' data the tables point at (tentative definitions in clf_extern.c) */")
        for v in sorted(datap):
            out.append("extern int DAT_%08x[];" % v)
        out.append("")
    out += body
    out.append("/* names of addresses inside the blocks, for this and other modules */")
    out.append("__asm__(")
    for n, block, off, addr in aliases:
        # file-scope asm names are Mach-O names: asm_convert.py strips one leading
        # underscore, so the C name _DAT_x is written __DAT_x (integration round 1)
        sym = "_" + n if n.startswith("_") else n
        out.append('\t".globl %s\\n.set %s, %s + 0x%x\\n"  /* 0x%08x */' % (sym, sym, block, off, addr))
    out.append(");")
    path = os.path.join(ROOT, "src", "hopper", "Hopper", "hopper_data.c")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("gen_hopper_data: %d aliases, %d strings, %d functions, %d data pointers -> %s"
          % (len(aliases), len(strings), len(funcs), len(datap), path))


if __name__ == "__main__":
    main()
