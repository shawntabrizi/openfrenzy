/* MSVC rand(), inlined into the game: holdrand is the C library's seed at 0x00285630.
Ghidra prints the increment 0x269ec3 as "<string at 0x00269eb0> + 0x13". */
extern unsigned int DAT_00285630;
static inline int hop_rand(void)
{
	DAT_00285630 = DAT_00285630 * 0x343fdu + 0x269ec3u;
	return (int)((DAT_00285630 >> 16) & 0x7fff);
}

/* a float's bit pattern, for an undefined4 parameter that carries a float */
static inline unsigned int hop_fbits(float value)
{
	unsigned int bits;
	memcpy(&bits, &value, sizeof bits);
	return bits;
}

static inline float hop_bitsf(unsigned int bits)
{
	float value;
	memcpy(&value, &bits, sizeof value);
	return value;
}

/* a bdisplay colour from 0-255 components (the four shift tables of bdisplay) */
extern unsigned int DAT_002bce18[256];   /* red << 16 */
extern unsigned int DAT_002bc490[256];   /* green << 8 */
extern unsigned int DAT_002bd640[256];   /* blue */
extern unsigned int DAT_002bc898[256];   /* alpha << 24 */
#define HOP_ARGB(a, r, g, b) (DAT_002bc898[(a)] | DAT_002bce18[(r)] | DAT_002bc490[(g)] | DAT_002bd640[(b)])

/* actor: copy the position into the previous and pre-collision positions (no move this frame) */
static inline void hop_ActorSnap(void *actor)
{
	memcpy((char *)actor + 0x1a4, (char *)actor + 0xd0, 16);
	memcpy((char *)actor + 0x1b4, (char *)actor + 0xd0, 16);
}

/* charlib 0x000b4bd0 (CRColl_RayCastNormal): the original returns the ray cast's hit fraction
in ST0 (0 when nothing is hit), which charlib's prototype (void) drops; this copy returns it */
static inline float hop_RayCastNormal(float *start, float *delta, float *hit, float *normal)
{
	float *tri;
	float frac = CRColl_RayCast(start, delta, hit, &tri, NULL);

	if (0.0f < frac)
		memcpy(normal, tri + 12, 0x10);
	normal[3] = 1.0f;
	return frac;
}

