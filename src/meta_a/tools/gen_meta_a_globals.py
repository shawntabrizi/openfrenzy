#!/usr/bin/env python3
"""Generate src/meta_a/Meta/meta_a_globals.c: fallback definitions of the globals that
meta_a uses and nobody else defines yet.

Usage (from the repository root, needs orig/default.xbe):
    python3 -I src/meta_a/tools/gen_meta_a_globals.py

Input: the declarations between "BEGIN FALLBACK" and "END FALLBACK" in
src/meta_a/meta_a_globals.h (one per line, Ghidra names with the address).

Output, per name:
- in an initialised XBE section: a weak definition with the original bytes;
- in a zero-filled (.bss) part: a common (tentative) definition.
Weak and common symbols lose to a strong definition, so a module that owns the memory
replaces them at link time. A dword that looks like an address of the XBE image stops
the generator (pointers must become symbols; fail loud).
"""
import os
import re
import struct
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", ".."))
sys.path.insert(0, os.path.join(ROOT, "scripts"))
import xbe_data  # noqa: E402

HEADER = os.path.join(ROOT, "src", "meta_a", "meta_a_globals.h")
OUT = os.path.join(ROOT, "src", "meta_a", "Meta", "meta_a_globals.c")

SIZES = {"char": 1, "unsigned char": 1, "short": 2, "unsigned short": 2, "int": 4,
         "unsigned int": 4, "float": 4, "void *": 4}
DECL = re.compile(r"^extern\s+(unsigned char|unsigned short|unsigned int|char|short|int|float|void \*)\s*(.*?);")
NAME = re.compile(r"^\**\s*((?:_?DAT|s_[A-Za-z0-9_]*?|PTR_[A-Za-z0-9_]*?)_(00[0-9a-f]{6}))\s*((?:\[[^\]]*\])*)$")
# addresses whose initial value may hold a dword in the image range (checked by hand)
POINTER_FREE_OK = {
    "s_aisteam1_00290f00",  # CSpriteDef: +0x44 numFrames/flags (0x00020000)
    "DAT_002b0d30",         # CSpriteDef: +0x44 numFrames/flags (0x00010000)
}


def main():
    text = open(HEADER).read()
    body = text[text.index("/* BEGIN FALLBACK */"):text.index("/* END FALLBACK */")]
    data, secs = xbe_data.load()
    at = xbe_data.reader(data, secs)
    out = []
    extents = []
    for line in body.splitlines():
        m = DECL.match(line.strip())
        if not m:
            continue
        ctype = m.group(1)
        for item in m.group(2).split(","):
            n = NAME.match(item.strip())
            if not n:
                raise SystemExit("gen_meta_a_globals: cannot parse %r" % item)
            name, addr, dims = n.group(1), int(n.group(2), 16), n.group(3)
            size = SIZES[ctype]
            for d in re.findall(r"\[([^\]]*)\]", dims):
                size *= int(d, 0)
            extents.append((addr, addr + size, name))
            sec = None
            for sname, va, vs, ra, rs in secs:
                if va <= addr < va + vs:
                    sec = (sname, va, vs, ra, rs)
            if sec is None:
                raise SystemExit("gen_meta_a_globals: %s is in no section" % name)
            sname, va, vs, ra, rs = sec
            initialised = addr - va < rs
            if initialised and addr + size - va > rs:
                raise SystemExit("gen_meta_a_globals: %s crosses the end of the raw data" % name)
            if not initialised:
                out.append("unsigned char %s[0x%x] __attribute__((aligned(4))); /* 0x%08x %s (bss) */"
                           % (name, size, addr, sname))
                continue
            raw = at(addr, size)
            for i in range(0, size - 3, 4):
                v, = struct.unpack_from("<I", raw, i)
                if 0x10000 <= v < 0x30b000 and name not in POINTER_FREE_OK:
                    raise SystemExit("gen_meta_a_globals: %s+0x%x = 0x%08x looks like a pointer"
                                     % (name, i, v))
            values = ", ".join("0x%02x" % b for b in raw)
            out.append("__attribute__((weak, aligned(4))) unsigned char %s[0x%x] = { %s }; /* 0x%08x %s */"
                       % (name, size, values, addr, sname))
    extents.sort()
    for (a0, e0, n0), (a1, e1, n1) in zip(extents, extents[1:]):
        if a1 < e0:
            raise SystemExit("gen_meta_a_globals: %s overlaps %s" % (n0, n1))
    with open(OUT, "w") as f:
        f.write("/* generated by src/meta_a/tools/gen_meta_a_globals.py from orig/default.xbe and\n"
                "   src/meta_a/meta_a_globals.h; do not edit. Fallback definitions: see the header. */\n\n")
        for line in out:
            f.write(line + "\n")
    print("gen_meta_a_globals: %d globals" % len(out))


if __name__ == "__main__":
    main()
