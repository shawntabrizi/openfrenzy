#!/usr/bin/env python3
"""Generate the game image's declarations, weak stubs and static-constructor list.

Usage: gen_game_decls.py --table src/include/of_functions.tsv --src src --out <dir> [--check]

Inputs
  of_functions.tsv   one row per original game/engine function (scripts/gen_function_table.py)
  src/<module>/**/*.decls
                     prototype overrides, owned by the module whose directory holds the file.
                     One per line:  <addr> <C prototype>;   for example
                       0002cd80 void Core_Init(void);
                       00027f10 int CGameMode_Root_Pushed(struct CGameMode_Root *self, int mode);
                     Use only of_types.h / C types and "struct Name *". A function may be
                     renamed; FUN_<addr> then becomes a macro for the new name.
Outputs
  of_decls.h         prototypes of all functions (+ "#define FUN_<addr> <name>" for renamed ones)
  of_stubs.c         a weak definition of every function that logs UNIMPLEMENTED and returns 0;
                     a real definition anywhere in src/ replaces it at link time
  of_crt_init.c      of_run_static_constructors(): the static constructors in _cinit order

The check fails loudly (exit 1) when a .decls file names an unknown address, an address of
another module, or an address twice.
"""
import argparse
import os
import re
import sys

PROTO_RE = re.compile(r"^\s*(?P<ret>.+?)\s*\b(?P<name>[A-Za-z_]\w*)\s*\((?P<params>.*)\)\s*;?\s*$")


def read_table(path):
    rows = []
    for line in open(path, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        addr, module, src_file, directory, confidence, size, crt, ghidra, proto = \
            line.rstrip("\n").split("\t")
        rows.append(dict(addr=addr, module=module, file=src_file, dir=directory, crt=crt,
                         ghidra=ghidra, proto=proto))
    return rows


def read_overrides(src, by_addr):
    overrides = {}
    errors = []
    for top in sorted(os.listdir(src)):
        base = os.path.join(src, top)
        if not os.path.isdir(base):
            continue
        for dirpath, _, files in os.walk(base):
            for name in sorted(files):
                if not name.endswith(".decls"):
                    continue
                path = os.path.join(dirpath, name)
                rel = os.path.relpath(path, src)
                for number, line in enumerate(open(path, encoding="utf-8"), 1):
                    line = line.split("#", 1)[0].strip()
                    if not line:
                        continue
                    where = "%s:%d" % (rel, number)
                    parts = line.split(None, 1)
                    addr = parts[0].lower().replace("0x", "").zfill(8)
                    if len(parts) < 2 or not PROTO_RE.match(parts[1]):
                        errors.append("%s: expected '<addr> <prototype>;'" % where)
                        continue
                    row = by_addr.get(addr)
                    if row is None:
                        errors.append("%s: 0x%s is not a game/engine function" % (where, addr))
                    elif row["module"] != top:
                        errors.append("%s: 0x%s belongs to module %s, not %s" % (where, addr, row["module"], top))
                    elif addr in overrides:
                        errors.append("%s: 0x%s already declared in %s" % (where, addr, overrides[addr][1]))
                    else:
                        overrides[addr] = (parts[1].rstrip(";").strip(), where)
    return overrides, errors


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--table", required=True)
    ap.add_argument("--src", required=True)
    ap.add_argument("--out")
    ap.add_argument("--check", action="store_true", help="only validate the .decls files")
    args = ap.parse_args()

    rows = read_table(args.table)
    by_addr = {r["addr"]: r for r in rows}
    overrides, errors = read_overrides(args.src, by_addr)
    names = {}
    for addr, (proto, where) in overrides.items():
        name = PROTO_RE.match(proto).group("name")
        if name in names:
            errors.append("%s: name %s already used for 0x%s" % (where, name, names[name]))
        names[name] = addr
    if errors:
        for e in errors:
            print("gen_game_decls: error: " + e, file=sys.stderr)
        return 1
    if args.check:
        print("gen_game_decls: %d overrides ok" % len(overrides))
        return 0

    decls = ["/* generated by port/macos/tools/gen_game_decls.py from src/include/of_functions.tsv",
             "   and the modules' .decls files; do not edit */", "#ifndef OPENFRENZY_DECLS_H",
             "#define OPENFRENZY_DECLS_H", ""]
    structs = set()
    stubs = ["/* generated by port/macos/tools/gen_game_decls.py; do not edit */",
             '#include "of_types.h"', "",
             "void of_unimplemented(unsigned int address, const char *name);", ""]
    body = []
    for r in rows:
        proto = overrides[r["addr"]][0] if r["addr"] in overrides else r["proto"]
        m = PROTO_RE.match(proto)
        name, ret = m.group("name"), m.group("ret").strip()
        structs.update(re.findall(r"\bstruct\s+(\w+)", proto))
        src_note = r["file"] if r["file"] != "-" else r["dir"]
        body.append("/* 0x%s %s %s */" % (r["addr"], r["module"], src_note))
        body.append(proto + ";")
        fun = "FUN_" + r["addr"]
        if name != fun:
            body.append("#define %s %s" % (fun, name))
        if ret == "void":
            ret_stmt = ""
        elif "*" in ret:
            ret_stmt = " return (%s)0;" % ret
        elif ret.startswith("struct "):
            ret_stmt = " %s result = {0}; return result;" % ret
        else:
            ret_stmt = " return (%s)0;" % ret
        stubs.append("__attribute__((weak)) %s %s(void) { of_unimplemented(0x%s, \"%s\");%s }"
                     % (ret, name, r["addr"], name, ret_stmt))
    decls += ["struct %s;" % s for s in sorted(structs)] + [""] + body + ["", "#endif"]
    stub_structs = sorted(set(re.findall(r"\bstruct\s+(\w+)", "\n".join(stubs))))
    stubs[3:3] = ["struct %s;" % s for s in stub_structs]

    crt = sorted((int(r["crt"]), r["addr"]) for r in rows if r["crt"] != "-")
    ctor = ["/* generated by port/macos/tools/gen_game_decls.py; do not edit */",
            "/* The static constructors ($E functions) in the order _cinit (0x000340f8) runs them:",
            "   the .CRT$XC table at 0x00281750 (src/include/of_functions.tsv, column crt). */",
            '#include "of_game.h"', "", "void of_run_static_constructors(void)", "{"]
    ctor += ["\tFUN_%s();" % a for _, a in crt]
    ctor += ["}"]

    os.makedirs(args.out, exist_ok=True)

    def write(name, lines):
        path = os.path.join(args.out, name)
        text = "\n".join(lines) + "\n"
        if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
            with open(path, "w", encoding="utf-8") as fh:
                fh.write(text)

    write("of_decls.h", decls)
    write("of_stubs.c", stubs)
    write("of_crt_init.c", ctor)
    print("gen_game_decls: %d functions, %d overrides, %d static constructors"
          % (len(rows), len(overrides), len(crt)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
