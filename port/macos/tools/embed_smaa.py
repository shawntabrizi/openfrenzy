#!/usr/bin/env python3
# After ref/OpenCE (231708d) tools/embed_assets.py (CC0), SMAA part only.
"""Embeds SMAA's shader and lookup textures (port/third_party/smaa) in the
platform layer as C data, as src/d3d8/xgpu_post.c declares them:

    embed_smaa.py SMAA_DIRECTORY OUTPUT.c

- xgpu_smaa_shader: SMAA.hlsl's text, ending in a NUL. Bytes above 127 (two
  in its comments) become spaces: GLSL ES accepts only ASCII.
- xgpu_smaa_area_texture, xgpu_smaa_search_texture: the texels of
  area_tex.zlib (160x560, two channels) and search_tex.zlib (64x16, one
  channel), inflated here, so the guest needs no zlib.

Each array is 32-bit words, not bytes (as OpenCE's embed_assets.py), and
each *_size is its size in bytes before padding.
"""

import struct
import sys
import zlib
from pathlib import Path

AREA_SIZE = 160 * 560 * 2
SEARCH_SIZE = 64 * 16


def words(data: bytes) -> str:
    padded = data + b"\0" * (-len(data) % 4)
    values = struct.unpack(f"<{len(padded) // 4}I", padded)
    lines = []
    for start in range(0, len(values), 8):
        lines.append("\t" + ", ".join(f"0x{value:08x}u" for value in values[start:start + 8]) + ",")
    return "\n".join(lines)


def array(name: str, data: bytes) -> str:
    return (f"const unsigned int {name}[] =\n{{\n{words(data)}\n}};\n"
            f"const unsigned long {name}_size = {len(data)}ul;\n\n")


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    source = Path(sys.argv[1])
    shader = bytes(b if b < 128 else 0x20 for b in (source / "SMAA.hlsl").read_bytes()) + b"\0"
    area = zlib.decompress((source / "area_tex.zlib").read_bytes())
    search = zlib.decompress((source / "search_tex.zlib").read_bytes())
    if len(area) != AREA_SIZE or len(search) != SEARCH_SIZE:
        print(f"embed_smaa: lookup textures are {len(area)} and {len(search)} bytes, "
              f"not {AREA_SIZE} and {SEARCH_SIZE}", file=sys.stderr)
        return 1
    text = ("/* generated by port/macos/tools/embed_smaa.py from port/third_party/smaa (MIT) */\n\n" +
            array("xgpu_smaa_shader", shader) + array("xgpu_smaa_area_texture", area) +
            array("xgpu_smaa_search_texture", search))
    Path(sys.argv[2]).write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
