#!/usr/bin/env python3
"""Generate src/runtime/entry/xdk_entry_points.inc.

The XBE statically links the XDK libraries (sections D3D, DSOUND, XGRPH, XPP).
The port does not decompile them: game code that calls into them is routed to
the OpenCE-derived HLE layer in src/<platform modules>. This script writes one X-macro
row per library function that matters:

  XDK_ENTRY(address, section, xbe_name, hle_name, kind)

kind:
  HLE       the HLE layer defines hle_name (exact XDK name, or identified below)
  MISSING   called from game code (.text), but the HLE layer has no hle_name yet
  UNKNOWN   called from game code, unnamed by XbSymbolDatabase, not identified
  INTERNAL  named, but only called from inside the library: no game call to route

Rows: every named function in those sections, plus every unnamed one that game
code calls. Inputs: export/functions.jsonl and the list of symbols the HLE
objects define (llvm-nm of src/runtime/build_check.sh's objects).

Usage: gen_xdk_entry_points.py <functions.jsonl> <hle_symbols.txt> <output.inc>
"""

import json
import sys

SECTIONS = ("D3D", "DSOUND", "XGRPH", "XPP")

# Unnamed (FUN_) functions identified by reading export/funcs/<addr>.c.
IDENTIFIED = {
    # __fastcall (stage, state, value): ORs the dirty bit and stores into
    # D3D_g_DeferredTextureState[stage * 0x20 + state]
    "001f6700": "D3DDevice_SetTextureState_Deferred",
    # the XBE names it D3D_GetDeviceCaps; the HLE (d3d8_gl.c) is Direct3D_GetDeviceCaps
    "002022f0": "Direct3D_GetDeviceCaps",
    # returns 1 (the Xbox's IDirect3D8 is a dummy object): Direct3DCreate8 (d3d8_extra.h)
    "002022e0": "Direct3DCreate8",
    # XGBuffer: decrements the reference count at +0, frees +4 and itself at zero
    "0022184b": "XGBuffer_Release",
    # XGBuffer: returns the data pointer at +4
    "00221874": "XGBuffer_GetBufferPointer",
    # assembles vertex shader text (d3d8/xgraphics.c)
    "0022835a": "XGAssembleShader",
}


def main() -> None:
    functions_path, symbols_path, output_path = sys.argv[1:4]
    functions = {}
    with open(functions_path, encoding="utf-8") as handle:
        for line in handle:
            entry = json.loads(line)
            functions[entry["addr"]] = entry
    with open(symbols_path, encoding="utf-8") as handle:
        hle = {line.split()[0] for line in handle if line.strip()}

    rows = []
    counts = {}
    for address, entry in sorted(functions.items()):
        section = entry["section"]
        if section not in SECTIONS:
            continue
        name = entry["name"]
        named = not name.startswith("FUN_") and not name.startswith("thunk_FUN_")
        game_callers = [c for c in entry["callers"] if c in functions and functions[c]["section"] == ".text"]
        if not named and not game_callers:
            continue
        target = IDENTIFIED.get(address, name if named else None)
        if target and target in hle:
            kind = "HLE"
        elif game_callers:
            kind = "MISSING" if named or address in IDENTIFIED else "UNKNOWN"
        else:
            kind = "INTERNAL"
        counts[(section, kind)] = counts.get((section, kind), 0) + 1
        hle_name = target if kind == "HLE" else None
        c_name = name.replace("\\", "\\\\").replace('"', '\\"')
        rows.append(
            f'XDK_ENTRY(0x{address}, "{section}", "{c_name}", '
            f'{hle_name if hle_name else "NULL"}, {kind}) /* game callers: {len(game_callers)} */'
        )

    summary = ", ".join(f"{s} {k} {n}" for (s, k), n in sorted(counts.items()))
    with open(output_path, "w", encoding="utf-8") as out:
        out.write("/* Generated by scripts/gen_xdk_entry_points.py; do not edit.\n")
        out.write(f"   {summary} */\n\n")
        out.write("\n".join(rows))
        out.write("\n")


if __name__ == "__main__":
    main()
