#!/usr/bin/env python3
"""Find globals whose storage is split between modules.

Several modules keep their globals in one block with the original layout (of_<id>_bss,
of_<id>_data, ...) and export assembler aliases (DAT_<addr> = block + offset) for the
names that Ghidra gave. A module that uses a DAT_<addr> name that the owner did not alias
gets its own common/weak copy, so the two modules read and write different memory.

This script reads the linked guest image, infers the original start address of each block
from the aliases that it already has, and lists every DAT_/_DAT_ symbol whose address is
inside a block's original range but whose storage is not the matching block byte.

Usage: python3 -I scripts/check_split_globals.py build/openfrenzy_guest.elf [--emit FILE]
--emit writes the missing aliases as a C file of top-level asm (.set) statements.
Exit status 1 when split symbols remain (after --emit, 0).
"""
import collections
import glob
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
NM = os.environ.get("OPENFRENZY_NM", "/opt/homebrew/opt/llvm@22/bin/llvm-nm")
# deliberate exclusions, documented by the owners
KNOWN = {
    # classlib_fx excludes [0x00290d14, 0x00290d54) from of_clf_data; classlib_ui owns it
    ("of_clf_data", a) for a in range(0x00290D14, 0x00290D54)
}


def block_sizes():
    sizes = {}
    decl = re.compile(r"(unsigned char|uint32_t)\s+(of_[a-z0-9_]+_(?:bss|data\d*|tweaks))\[(0x[0-9a-fA-F]+|\d+)\]")
    for path in glob.glob(os.path.join(ROOT, "src", "**", "*.c"), recursive=True):
        if os.sep + "tests" + os.sep in path:
            continue
        for m in decl.finditer(open(path, errors="replace").read()):
            n = int(m.group(3), 0) * (4 if m.group(1) == "uint32_t" else 1)
            sizes[m.group(2)] = max(sizes.get(m.group(2), 0), n)
    return sizes


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 2
    sizes = block_sizes()
    out = subprocess.run([NM, "-n", sys.argv[1]], capture_output=True, text=True, check=True).stdout
    blocks, syms = {}, []
    for line in out.splitlines():
        p = line.split()
        if len(p) != 3:
            continue
        addr, name = int(p[0], 16), p[2]
        if name in sizes:
            blocks[name] = (addr, sizes[name])
        m = re.match(r"^_?DAT_([0-9a-f]{8})$", name)
        if m:
            syms.append((int(m.group(1), 16), addr, name))
    starts = {}
    for b, (base, size) in blocks.items():
        votes = collections.Counter(orig - (a - base) for orig, a, _ in syms if base <= a < base + size)
        if votes:
            starts[b] = (votes.most_common(1)[0][0], base, size)
    bad = []
    for orig, a, name in syms:
        for b, (start, base, size) in starts.items():
            if start <= orig < start + size and (b, orig) not in KNOWN and a != base + (orig - start):
                bad.append((b, name, orig - start))
    for b, name, off in sorted(bad):
        print(f"split: {name} should be {b} + 0x{off:x}")
    if "--emit" in sys.argv:
        path = sys.argv[sys.argv.index("--emit") + 1]
        with open(path, "w") as f:
            f.write("/* generated by scripts/check_split_globals.py; see its docstring. Aliases that\n"
                    "   the owners' data generators do not emit yet (integration). */\n")
            f.write("__asm__(\n")
            for b, name, off in sorted(bad):
                f.write(f'\t".globl {name}\\n.set {name}, {b} + 0x{off:x}\\n"\n')
            f.write(");\n")
        return 0
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
